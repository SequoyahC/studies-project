/**
 * OPERATORS:
 * 
 * 0: Operators are for Mathematical and Logical Computations
 * The Assignment Operator = assigns values
 * The Addition Operator + adds values
 * The Multiplication Operator * multiplies values
 * The Comparison Operator > compares values
 * 
 */
// Assignment Operator //
let x = 10;   // assigns the value 10 to x

// Addition Operator //
let x = 5;         
let y = 2;
let z = x + y;      // => 7

// Multiplication Operator //
let x = 5;
let y = 2;
let z = x * y;      // => 10


// Comparison Operator //
let text1 = "A";
let text2 = "B";                // All conditional operators can be used on both numbers and strings.
let result = text1 < text2;     // => Is A less than B? true